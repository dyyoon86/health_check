// 자세 가이드: 그림(SVG 직접 작성) + 포인트 + 흔한 실수 + 영상 검색 링크
// 좌표계: 패널 폭 130(기본), 바닥 y=120
const T = (x, y, t, a = 'middle') => `<text x="${x}" y="${y}" class="at" text-anchor="${a}">${t}</text>`;
const A = (x1, y1, x2, y2) => `<line x1="${x1}" y1="${y1}" x2="${x2}" y2="${y2}" class="ar"/>`;
const D = (x1, y1, x2, y2) => `<line x1="${x1}" y1="${y1}" x2="${x2}" y2="${y2}" class="ds"/>`;
const PR = (x1, y1, x2, y2) => `<line x1="${x1}" y1="${y1}" x2="${x2}" y2="${y2}" class="pr"/>`;
const RC = (x, y, w, h) => `<rect x="${x}" y="${y}" width="${w}" height="${h}" class="rc"/>`;
const CI = (x, y, r) => `<circle cx="${x}" cy="${y}" r="${r}" class="ci"/>`;

function svgPanels(panels) {
  const H = 152;
  let total = 0;
  panels.forEach(p => total += (p.w || 130));
  let s = `<svg viewBox="0 0 ${total} ${H}" class="fig" role="img" style="max-width:${total * 1.7}px"><defs><marker id="ah" viewBox="0 0 10 10" refX="8" refY="5" markerWidth="5" markerHeight="5" orient="auto-start-reverse"><path d="M0,0L10,5L0,10z" fill="currentColor"/></marker></defs>`;
  let ox = 0;
  panels.forEach((p, i) => {
    const w = p.w || 130;
    if (i > 0) s += `<line x1="${ox}" y1="22" x2="${ox}" y2="132" class="sep"/>`;
    s += `<text x="${ox + w / 2}" y="13" text-anchor="middle" class="cap">${p.cap}</text>`;
    s += `<g transform="translate(${ox},10)">`;
    if (!p.noGround) s += `<line x1="4" y1="120" x2="${w - 4}" y2="120" class="gr"/>`;
    (p.s || []).forEach(pl => s += `<polyline points="${pl.map(q => q.join(',')).join(' ')}" class="b"/>`);
    (p.q || []).forEach(([a, c, b]) => s += `<path d="M${a.join(',')} Q${c.join(',')} ${b.join(',')}" class="b"/>`);
    if (p.h) s += `<circle cx="${p.h[0]}" cy="${p.h[1]}" r="7" class="hd"/>`;
    s += p.x || '';
    s += '</g>';
    ox += w;
  });
  return s + '</svg>';
}

