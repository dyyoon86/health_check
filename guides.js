function guideKey(t) {
  if (t.includes('교차윗몸')) return 'situp';
  if (t.includes('앉아윗몸앞으로굽히기') || t.startsWith('유연성')) return 'flex';
  if (t.includes('스쿼트점프')) return 'squatjump';
  if (t.includes('스쿼트')) return 'squat';
  if (t.includes('벽 푸시업')) return 'wallpush';
  if (t.includes('무릎 푸시업')) return 'kneepush';
  if (t.includes('악력')) return 'grip';
  if (t.includes('데드행')) return 'hang';
  if (t.includes('멀리뛰기')) return 'jump';
  if (t.includes('10m')) return 'agility';
  if (t.includes('셔틀런') || t.includes('왕복오래달리기')) return 'shuttle';
  if (t.includes('스트레칭')) return 'stretch';
  if (t.includes('준비운동')) return 'warm';
  if (t.includes('걷기') || t.includes('조깅')) return 'run';
  return null;
}

function guideHTML(key) {
  const g = GUIDES[key];
  let h = `<h2>${g.title}</h2>`;
  g.parts.forEach(p => {
    if (p.name) h += `<div class="sec">${p.name}</div>`;
    if (p.panels) h += svgPanels(p.panels);
    h += `<ul class="cues">${p.cues.map(c => `<li>${c}</li>`).join('')}</ul>`;
  });
  if (g.bad) h += `<div class="sec">흔한 실수</div><ul class="bad">${g.bad.map(c => `<li>${c}</li>`).join('')}</ul>`;
  if (g.note) h += `<p class="warn">${g.note}</p>`;
  h += `<p><a href="https://www.youtube.com/results?search_query=${encodeURIComponent(g.yt)}" target="_blank" rel="noopener">▶ 유튜브에서 "${g.yt}" 영상 보기</a></p>`;
  return h;
}
